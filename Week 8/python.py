# Operators

# Addition (+)
# Subtraction (-)
# Multiplication (*)
# Division (/)
# Modulus (%)
# Exponentiation (**)

x = 10
y = 2

print(x + y)  # Output: 12
print(x - y)  # Output: 8
print(x * y)  # Output: 20
print(x / y)  # Output: 5.0
print(x % y)  # Output: 0
print(x ** y)  # Output: 100

x += 2